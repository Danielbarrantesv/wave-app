/** Supported languages. */
enum class AppLanguage(val code: String, val displayName: String, val stringKey: String) {
    ES("es", "Español", "lang_es"),
    EN("en", "English", "lang_en"),
    JA("ja", "日本語", "lang_ja"),
    DE("de", "Deutsch", "lang_de"),
    FR("fr", "Français", "lang_fr"),
    KO("ko", "한국어", "lang_ko");

    companion object {
        fun fromCode(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: ES
    }
}

