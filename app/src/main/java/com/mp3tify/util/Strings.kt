    private val all: Map<String, Map<String, String>> = mapOf(
        "es" to es,
        "en" to en,
        "ja" to ja,
        "de" to de,
        "fr" to fr,
        "ko" to ko
    )

    /** Translate [key] for [langCode]; falls back to "es" and then to the raw key. */
    fun t(key: String, langCode: String): String {
        val lang = langCode.ifBlank { "es" }
        return all[lang]?.get(key)
            ?: all["es"]?.get(key)
            ?: key
    }

    /** Translate with String.format-style placeholders (e.g. "%1\$d"). */
    fun f(key: String, langCode: String, vararg args: Any): String {
        return try {
            String.format(t(key, langCode), *args)
        } catch (e: Exception) {
            t(key, langCode)
        }
    }
